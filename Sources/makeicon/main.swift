import AppKit
import CoreText

// Regenerates Resources/icon.svg. The lettering is emitted as outlines rather than a
// <text> element because SVG renderers disagree about font resolution — AppKit's, the
// one that rasterizes the .icns, substitutes a sans-serif for any font-family it is given.

let fontName = "CourierNewPS-BoldMT"
let letters = "UTC"
let canvas: CGFloat = 1024
let lettersWidth: CGFloat = 620

let font = CTFontCreateWithName(fontName as CFString, 1000, nil)

var glyphs = [CGGlyph](repeating: 0, count: letters.count)
var characters = Array(letters.utf16)
guard CTFontGetGlyphsForCharacters(font, &characters, &glyphs, characters.count) else {
    FileHandle.standardError.write(Data("\(fontName) has no glyphs for \"\(letters)\"\n".utf8))
    exit(1)
}

var advances = [CGSize](repeating: .zero, count: glyphs.count)
CTFontGetAdvancesForGlyphs(font, .horizontal, &glyphs, &advances, glyphs.count)

let outline = CGMutablePath()
var pen: CGFloat = 0
for (glyph, advance) in zip(glyphs, advances) {
    if let path = CTFontCreatePathForGlyph(font, glyph, nil) {
        outline.addPath(path, transform: CGAffineTransform(translationX: pen, y: 0))
    }
    pen += advance.width
}

let bounds = outline.boundingBoxOfPath
let scale = lettersWidth / bounds.width
// Flips the y axis (CoreText points up, SVG points down) and centres the outline.
var transform = CGAffineTransform.identity
    .translatedBy(x: canvas / 2, y: canvas / 2)
    .scaledBy(x: scale, y: -scale)
    .translatedBy(x: -bounds.midX, y: -bounds.midY)
guard let placed = outline.copy(using: &transform) else {
    FileHandle.standardError.write(Data("cannot transform outline\n".utf8))
    exit(1)
}

func number(_ value: CGFloat) -> String {
    let rounded = (value * 100).rounded() / 100
    return rounded == rounded.rounded() ? String(Int(rounded)) : String(format: "%g", rounded)
}

var commands: [String] = []
placed.applyWithBlock { element in
    let points = element.pointee.points
    switch element.pointee.type {
    case .moveToPoint:
        commands.append("M\(number(points[0].x)) \(number(points[0].y))")
    case .addLineToPoint:
        commands.append("L\(number(points[0].x)) \(number(points[0].y))")
    case .addQuadCurveToPoint:
        commands.append("Q\(number(points[0].x)) \(number(points[0].y)) \(number(points[1].x)) \(number(points[1].y))")
    case .addCurveToPoint:
        commands.append("C\(number(points[0].x)) \(number(points[0].y)) \(number(points[1].x)) \(number(points[1].y)) \(number(points[2].x)) \(number(points[2].y))")
    case .closeSubpath:
        commands.append("Z")
    @unknown default:
        break
    }
}

let svg = """
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by `swift run makeicon`: "\(letters)" outlined from \(fontName). -->
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs>
    <linearGradient id="face" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#3b4252"/>
      <stop offset="1" stop-color="#1c2029"/>
    </linearGradient>
  </defs>
  <!-- An 824pt squircle inset in a 1024pt canvas is the macOS app icon grid. -->
  <rect x="100" y="100" width="824" height="824" rx="185" ry="185" fill="url(#face)"/>
  <rect x="100.5" y="100.5" width="823" height="823" rx="184.5" ry="184.5" fill="none" stroke="#5a6377" stroke-width="1"/>
  <path fill="#f2f4f8" fill-rule="nonzero" d="\(commands.joined(separator: " "))"/>
</svg>

"""

let destination = URL(fileURLWithPath: "Resources/icon.svg")
try svg.write(to: destination, atomically: true, encoding: .utf8)
print("wrote \(destination.path)")
